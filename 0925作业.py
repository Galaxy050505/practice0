"""写一个程序删除一个非空字符串的第n个字符（提示：需要用到字符串截取操作符[,]，见本PPT第16页）
BMI是一种健康指标，可以通过体重（以千克为单位）除以身高（以米为单位）的平方来计算。编写一个程序，
提示用户输入体重（以磅为单位）和身高（以英寸为单位），计算并显示BMI。一磅等于0.45359237千克，一英寸等于0.0254米。
"""
#Q1
a=input('请输入一非空字符串:')
n=int(input('要删除的字符下标?:'))
print(a[0:n]+a[n+1:])

