num1=1
str1='10'
#float()--轉浮點數
print(type(float(num1)))#float
print(float(num1))#1.0
print(float(str1))#10.0
#str()--轉字符串
print(type(str(num1)))#str
print(str(num1))#1
print(str(str1))#10
#tuple()--轉元組
list1=[10,20,30]
print(tuple(list1))
#list()--轉列表
tuple1=(100,200,300)
print(list(tuple1))
#eval()--計算在字符串中有效的python表達式並返回一個對象
str2='1'
str3='1.1'
str4='(1000,2000,3000)'
str5='[1000,2000,3000]'
#也就是說把字符串裡的數據轉換回原本的類型
print(type(eval(str2)))
print(type(eval(str3)))
print(type(eval(str4)))
print(type(eval(str5)))