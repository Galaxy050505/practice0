#序列[開始:結束:間隔(默認1)]
str1='abcdefg'
print(str1)
print(str1[0])
print(str1[1])
print(str1[0:6:2])
print(str1[1:4])#默認間隔為1
print(str1[:5])#不寫開始默認從頭(0)
print(str1[2:])#不寫結束默認到最後
print(str1[:])#頭尾都沒有默認選取全部
print(str1[::-1])#若間隔為負數代表倒敘
print(str1[-4:-1])#結束-1表示最後一個數據，依次向前類推
#正索引:0123456//負索引:-7,-6,-5,-4,-3,-2,-1
#所以[-4:-1]為d始g結束,得def
#終極測試
print(str1[-4:-1:1])#還是def
print(str1[-4:-1:-1])#不能選取出數據:從-4到-1結束,選取方向為從左到右
#但是-1間隔為從右向左選取
#***如果選取方向和間隔方向衝突則無法選取***ex:[-1:-4:1]、[-4:-1:-1]
print(str1[-1:-4:-1])#gfe