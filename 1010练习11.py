salary = float(input())

if salary <= 2000.00:
    print("Isento")
elif salary <= 3000.00:
    # 只有超出2000的部分需要交 8% 的税
    tax = (salary - 2000.00) * 0.08
    print(f"R$ {tax:.2f}")
elif salary <= 4500.00:
    # 2000到3000的部分固定交税：1000 * 0.08 = 80
    # 超出3000的部分交 18%
    tax = 80.00 + (salary - 3000.00) * 0.18
    print(f"R$ {tax:.2f}")
else:
    # 2000到3000交80
    # 3000到4500交：(4500 - 3000) * 0.18 = 1500 * 0.18 = 270
    # 固定交税前两段：80 + 270 = 350
    # 超出4500的部分交 28%
    tax = 350.00 + (salary - 4500.00) * 0.28
    print(f"R$ {tax:.2f}")